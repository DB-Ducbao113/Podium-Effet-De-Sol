/**
 * Map connecting calendar round numbers (1 to 24) to circuit records.
 */
export const ROUND_TO_CIRCUIT_MAP: RoundCircuitMap = Object.values(CIRCUITS_DATA).reduce(
  (acc, circuit) => {
    if (circuit.round > 0) {
      acc[circuit.round] = circuit;
    }
    return acc;
  },
  {} as Record<number, CircuitData>,
);

/**
 * Retrieve circuit data by calendar round number.
 */
export function getCircuitByRound(round: number): CircuitData | undefined {
  return ROUND_TO_CIRCUIT_MAP[round];
}

/**
 * Retrieve circuit data by unique CircuitId.
 */
export function getCircuitById(id: CircuitId): CircuitData | undefined {
  return CIRCUITS_DATA[id];
}

/**
 * Fuzzy search / lookup circuit data by country, circuit name, or city.
 */
export function findCircuitByName(query: string): CircuitData | undefined {
  const q = query.toLowerCase().trim();
  return Object.values(CIRCUITS_DATA).find(
    (c) =>
      c.circuitName.toLowerCase().includes(q) ||
      c.officialName.toLowerCase().includes(q) ||
      c.city.toLowerCase().includes(q) ||
      c.country.toLowerCase().includes(q) ||
      c.countryCode.toLowerCase() === q,
  );
}
